<?php

namespace App\Api;

use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Routing\Route;
use Illuminate\Support\Facades\Route as Router;
use Illuminate\Support\Str;
use Illuminate\Validation\Rules\Enum;
use Illuminate\Validation\Rules\In;
use Illuminate\Validation\Rules\Password;
use ReflectionMethod;
use ReflectionNamedType;

/**
 * ENG-12: the OpenAPI document of the staff API (/api/v1, except /api/v1/public, which has its own hand-kept spec,
 * docs/openapi-public.yaml), generated from what the code really does, so it cannot drift:
 *
 *  - paths and methods from the registered routes, path parameters from their placeholders and constraints;
 *  - `x-authz`: the authorization each route declares (authz:permission,… / authenticated / public);
 *  - request bodies from the Form Request each action takes (its rules() become a JSON schema);
 *  - response bodies from the v1 Resource the action answers with (Resource::SHAPE), inside the usual envelope.
 *
 * `php artisan api:openapi` writes it (docs/openapi.json) and the typed client generated from it; OpenApiTest fails
 * the build when either is stale. What the generator cannot know (query filters of list endpoints, answers of
 * actions that build their JSON by hand) is described generically rather than guessed.
 */
class OpenApiSpec
{
    public const FILE = 'docs/openapi.json';

    /** @return array<string, mixed> */
    public static function build(): array
    {
        $paths = [];
        $ids = [];
        $routes = collect(Router::getRoutes()->getRoutes())
            ->filter(fn (Route $r) => str_starts_with($r->uri(), 'api/v1/') && ! str_starts_with($r->uri(), 'api/v1/public'))
            ->sortBy(fn (Route $r) => $r->uri().' '.implode(',', $r->methods()));

        foreach ($routes as $route) {
            $path = '/'.Str::after($route->uri(), 'api/v1/');
            $path = (string) preg_replace('/\{(\w+)\?\}/', '{$1}', $path);
            foreach (array_diff($route->methods(), ['HEAD']) as $method) {
                $op = self::operation($route, strtolower($method), $path);
                // one action on several routes or methods: the method tells them apart, then a counter if needed
                $id = $op['operationId'];
                if (isset($ids[$id])) {
                    $id .= Str::studly(strtolower($method));
                    $id .= isset($ids[$id]) ? ++$ids[$op['operationId']] : '';
                }
                $ids[$id] = $ids[$id] ?? 0;
                $op['operationId'] = $id;
                $paths[$path][strtolower($method)] = $op;
            }
        }
        ksort($paths);

        return self::objects([
            'openapi' => '3.0.3',
            'info' => ['title' => 'Law firm system: staff API', 'version' => (string) config('app.version', '1'),
                'description' => 'The API the web app uses (session cookie + XSRF token, Sanctum SPA). Generated by `php artisan api:openapi` (ENG-12); '
                    .'the public API for integrations is docs/openapi-public.yaml. `x-authz` is the authorization each operation requires.'],
            'servers' => [['url' => '/api/v1']],
            'paths' => $paths,
            'components' => ['schemas' => self::schemas()],
        ]);
    }

    /** An empty `items` / `properties` must be a JSON object ({}), not a list ([]). */
    private static function objects(mixed $v, ?string $key = null): mixed
    {
        if (! is_array($v)) {
            return $v;
        }
        if ($v === [] && in_array($key, ['items', 'properties', 'data'], true)) {
            return new \stdClass;
        }
        foreach ($v as $k => $child) {
            $v[$k] = self::objects($child, is_string($k) ? $k : null);
        }

        return $v;
    }

    /** @return array<string, mixed> */
    private static function operation(Route $route, string $method, string $path): array
    {
        $action = $route->getActionName();
        [$controller, $fn] = str_contains($action, '@') ? explode('@', $action) : [null, null];
        $base = $controller ? Str::beforeLast(class_basename($controller), 'Controller') : 'Route';
        $op = [
            'operationId' => $fn ? lcfirst($base).ucfirst($fn) : Str::camel($method.' '.str_replace(['/', '{', '}', '-'], ' ', $path)),
            'tags' => [$base],
            'x-authz' => self::authz($route),
        ];
        $params = [];
        foreach ($route->parameterNames() as $name) {
            $numeric = isset($route->wheres[$name]) && preg_match('/^\[0-9\]\+$|^\\\\d\+$/', $route->wheres[$name]);
            $params[] = ['name' => $name, 'in' => 'path', 'required' => true, 'schema' => ['type' => $numeric ? 'integer' : 'string']];
        }
        if ($params) {
            $op['parameters'] = $params;
        }

        $reflection = $controller && method_exists($controller, $fn) ? new ReflectionMethod($controller, $fn) : null;
        if ($reflection && ($request = self::formRequest($reflection)) && in_array($method, ['post', 'put', 'patch', 'delete'], true)) {
            $schema = self::rulesSchema($request);
            if ($schema !== null) {
                $multipart = str_contains(json_encode($schema), '"format":"binary"');
                $op['requestBody'] = ['required' => ! empty($schema['required']),
                    'content' => [$multipart ? 'multipart/form-data' : 'application/json' => ['schema' => $schema]]];
            }
        } elseif ($reflection && ($request = self::formRequest($reflection)) && $method === 'get') {
            $schema = self::rulesSchema($request);
            foreach ($schema['properties'] ?? [] as $name => $s) {
                $op['parameters'][] = ['name' => $name, 'in' => 'query', 'required' => in_array($name, $schema['required'] ?? [], true), 'schema' => $s];
            }
        }

        $op['responses'] = ['200' => ['description' => 'Success', 'content' => ['application/json' => ['schema' => [
            'allOf' => [['$ref' => '#/components/schemas/ApiResponse'], ['type' => 'object', 'properties' => ['data' => self::answer($reflection)]]],
        ]]]]] + ['401' => ['description' => 'Not signed in'], '403' => ['description' => 'Not allowed (x-authz)'], '422' => ['description' => 'Invalid input or refused action (see `code`)']];

        return $op;
    }

    /** permission,… / authenticated / policy,… (staff), portal-session (a client signed in to the portal), or public */
    private static function authz(Route $route): string
    {
        $mw = array_filter($route->gatherMiddleware(), 'is_string');
        foreach ($mw as $m) {
            if (str_starts_with($m, 'authz:')) {
                return Str::after($m, 'authz:');
            }
        }

        // no staff authorization: either the client portal's own session, or a credential in the request itself (a signed
        // link, a webhook secret, a one-time code), or nothing (sign-in)
        return in_array('portal.session', $mw, true) ? 'portal-session' : 'public';
    }

    /** @return class-string<FormRequest>|null */
    private static function formRequest(ReflectionMethod $m): ?string
    {
        foreach ($m->getParameters() as $p) {
            $t = $p->getType();
            if ($t instanceof ReflectionNamedType && ! $t->isBuiltin() && is_subclass_of($t->getName(), FormRequest::class)) {
                return $t->getName();
            }
        }

        return null;
    }

    /** @return array<string, mixed> the `data` of the answer, from the Resource the action uses (if any) */
    private static function answer(?ReflectionMethod $m): array
    {
        if (! $m || ! $m->getFileName()) {
            return ['description' => 'See the endpoint'];
        }
        $source = implode('', array_slice(file($m->getFileName()) ?: [], $m->getStartLine() - 1, $m->getEndLine() - $m->getStartLine() + 1));
        if (! preg_match('/(\w+)Resource(::|\b)/', $source, $hit) || ! class_exists('App\\Http\\Resources\\V1\\'.$hit[1].'Resource')) {
            return ['description' => 'See the endpoint'];
        }
        $ref = ['$ref' => '#/components/schemas/'.$hit[1]];
        if (str_contains($source, 'paginatedOrFull(')) {
            return ['allOf' => [['$ref' => '#/components/schemas/Paginated'], ['type' => 'object', 'properties' => ['data' => ['type' => 'array', 'items' => $ref]]]]];
        }

        return str_contains($source, 'Resource::collection(') ? ['type' => 'array', 'items' => $ref] : $ref;
    }

    /**
     * A JSON schema from a Form Request's rules: types, required, nullable, enums, lengths, nested objects and lists.
     *
     * @param  class-string<FormRequest>  $class
     * @return array<string, mixed>|null null when the rules cannot be read outside a request
     */
    public static function rulesSchema(string $class): ?array
    {
        try {
            $request = new $class;
            $rules = method_exists($request, 'rules') ? $request->rules() : [];
        } catch (\Throwable) {
            return null;
        }
        $root = ['type' => 'object', 'properties' => []];
        ksort($rules);
        foreach ($rules as $key => $rule) {
            $list = is_string($rule) ? explode('|', $rule) : (array) $rule;
            [$schema, $required] = self::fieldSchema($list);
            self::place($root, explode('.', (string) $key), $schema, $required);
        }

        return $root;
    }

    /** @param array<string, mixed> $node */
    private static function place(array &$node, array $segments, array $schema, bool $required): void
    {
        $name = array_shift($segments);
        if ($name === '*') {
            $node['type'] = 'array';
            $node['items'] ??= [];
            if ($segments) {
                $node['items'] += ['type' => 'object', 'properties' => []];
                self::place($node['items'], $segments, $schema, $required);
            } else {
                $node['items'] = $schema + $node['items'];
            }

            return;
        }
        if (! $segments) {
            $node['properties'][$name] = $schema + ($node['properties'][$name] ?? []);
            if ($required) {
                $node['required'][] = $name;
            }

            return;
        }
        $child = $node['properties'][$name] ?? ['type' => 'object', 'properties' => []];
        if (($segments[0] ?? null) !== '*') {
            $child['type'] = 'object';
            $child['properties'] ??= [];
        }
        self::place($child, $segments, $schema, false);
        $node['properties'][$name] = $child;
    }

    /** @return array{0: array<string, mixed>, 1: bool} */
    private static function fieldSchema(array $rules): array
    {
        $s = [];
        $required = false;
        $numeric = false;
        foreach ($rules as $r) {
            if ($r instanceof In) {
                $values = (fn () => $this->values)->call($r);
                $s['enum'] = array_values(array_map(fn ($v) => $v instanceof \BackedEnum ? $v->value : $v, $values));

                continue;
            }
            if ($r instanceof Enum) {
                $type = (fn () => $this->type)->call($r);
                $s['enum'] = array_map(fn ($c) => $c->value, $type::cases());

                continue;
            }
            if ($r instanceof Password) {
                $applied = $r->appliedRules();
                $s['minLength'] = max((int) ($s['minLength'] ?? 0), (int) $applied['min']);
                $needs = array_keys(array_filter(['letters' => $applied['letters'], 'mixed case' => $applied['mixedCase'], 'numbers' => $applied['numbers'], 'symbols' => $applied['symbols']]));
                $needs && $s['description'] = 'Must contain '.implode(', ', $needs).'.';

                continue;
            }
            if (! is_string($r)) {
                continue;
            }
            [$name, $arg] = array_pad(explode(':', $r, 2), 2, null);
            match ($name) {
                'required' => $required = true,
                'nullable' => $s['nullable'] = true,
                'integer' => [$s['type'], $numeric] = ['integer', true],
                'numeric' => [$s['type'], $numeric] = ['number', true],
                'boolean', 'accepted' => $s['type'] = 'boolean',
                'array' => $s['type'] ??= 'array',
                'string' => $s['type'] ??= 'string',
                'email' => [$s['type'], $s['format']] = ['string', 'email'],
                'date' => [$s['type'], $s['format']] = ['string', 'date'],
                'date_format' => [$s['type'], $s['description']] = ['string', 'Date as '.$arg],
                'file', 'image', 'mimes', 'mimetypes' => [$s['type'], $s['format']] = ['string', 'binary'],
                'in' => $s['enum'] = array_map(fn ($v) => trim($v, '"'), str_getcsv((string) $arg)),
                default => null,
            };
            if (in_array($name, ['max', 'min'], true) && is_numeric($arg)) {
                $s[$name === 'max' ? ($numeric ? 'maximum' : 'maxLength') : ($numeric ? 'minimum' : 'minLength')] = $arg + 0;
            }
        }
        if (($s['type'] ?? null) === 'array') {
            $s['items'] = [];   // what the items are comes from a "field.*" rule, if there is one
        }
        if (($s['format'] ?? null) === 'binary' && isset($s['maxLength'])) {   // for a file, max is its size in kilobytes
            $s['description'] = 'At most '.$s['maxLength'].' KB';
            unset($s['maxLength'], $s['minLength']);
        }
        if (isset($s['maxLength'], $s['type']) && $s['type'] !== 'string') {
            unset($s['maxLength'], $s['minLength']);
        }

        return [$s, $required];
    }

    /** @return array<string, mixed> */
    private static function schemas(): array
    {
        $out = [
            'ApiResponse' => ['type' => 'object', 'required' => ['success', 'message'], 'properties' => [
                'success' => ['type' => 'boolean'], 'message' => ['type' => 'string'], 'data' => [],
                'code' => ['type' => 'string', 'description' => 'A machine-readable reason on some refusals'],
                'errors' => ['type' => 'object', 'additionalProperties' => ['type' => 'array', 'items' => ['type' => 'string']]],
            ]],
            'Paginated' => ['type' => 'object', 'properties' => ['data' => ['type' => 'array', 'items' => []],
                'current_page' => ['type' => 'integer'], 'last_page' => ['type' => 'integer'], 'per_page' => ['type' => 'integer'], 'total' => ['type' => 'integer']]],
        ];
        foreach (TypeScriptTypes::shapes() as $name => $shape) {
            $props = [];
            $required = [];
            foreach ($shape as $key => $type) {
                $nullable = str_starts_with($type, '?');
                $props[$key] = match (ltrim($type, '?')) {
                    'int' => ['type' => 'integer'],
                    'bool' => ['type' => 'boolean'],
                    'decimal' => ['type' => 'string', 'format' => 'decimal'],
                    'date' => ['type' => 'string', 'description' => 'd/m/Y'],
                    'int[]' => ['type' => 'array', 'items' => ['type' => 'integer']],
                    default => ['type' => 'string'],
                } + ($nullable ? ['nullable' => true] : []);
                $required[] = $key;
            }
            $out[$name] = ['type' => 'object', 'required' => $required, 'properties' => $props];
        }

        return $out;
    }

    public static function render(): string
    {
        return json_encode(self::build(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)."\n";
    }
}
