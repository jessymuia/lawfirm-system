<?php

namespace App\Api;

use Illuminate\Support\Str;

/**
 * ENG-12: a typed client for the staff API, generated from the OpenAPI document (OpenApiSpec), one function per
 * operation: path parameters first, then the request body (typed from the operation's Form Request) or query
 * parameters, then axios options. Each resolves to the answer's envelope, typed from the Resource it returns.
 */
class TypeScriptClient
{
    public const FILE = 'resources/js/src/api/client.generated.ts';

    /** @param array<string, mixed> $spec */
    public static function render(array $spec): string
    {
        $schemaNames = array_keys(TypeScriptTypes::shapes());
        $out = [
            '// Generated by `php artisan api:openapi` from docs/openapi.json (ENG-12). Do not edit by hand.',
            '/* eslint-disable */',
            "import type { AxiosRequestConfig } from 'axios';",
            "import api from '../api';",
            'import type { ApiResponse, Paginated, '.implode(', ', $schemaNames)." } from './types.generated';",
            '',
            'type Query = Record<string, string | number | boolean | null | undefined>;',
        ];
        foreach ($spec['paths'] as $path => $methods) {
            foreach ($methods as $method => $op) {
                $out = array_merge($out, self::operation($path, $method, $op));
            }
        }

        return implode("\n", $out)."\n";
    }

    private const RESERVED = ['case', 'class', 'default', 'delete', 'new', 'function', 'switch', 'var', 'void', 'with', 'in', 'do', 'if', 'for', 'import', 'export', 'return', 'this', 'typeof', 'enum'];

    /** A path parameter's name as a TypeScript argument (`case` -> `caseId`). */
    private static function arg(string $name): string
    {
        $n = Str::camel($name);

        return in_array($n, self::RESERVED, true) ? $n.'Id' : $n;
    }

    /** @return list<string> */
    private static function operation(string $path, string $method, array $op): array
    {
        $name = $op['operationId'];
        $lines = [''];
        $args = [];
        foreach ($op['parameters'] ?? [] as $p) {
            if ($p['in'] === 'path') {
                $args[] = self::arg($p['name']).': '.(($p['schema']['type'] ?? '') === 'integer' ? 'number' : 'string | number');
            }
        }
        $url = '`/api/v1'.preg_replace_callback('/\{(\w+)\}/', fn ($m) => '${'.self::arg($m[1]).'}', $path).'`';
        $bodyType = null;
        if (isset($op['requestBody'])) {
            $content = $op['requestBody']['content'];
            $schema = $content['application/json']['schema'] ?? $content['multipart/form-data']['schema'];
            $bodyType = Str::studly($name).'Body';
            $lines[] = "export type {$bodyType} = ".self::ts($schema, '').';';
            $args[] = isset($content['multipart/form-data']) ? "body: {$bodyType} | FormData" : 'body'.($op['requestBody']['required'] ? '' : '?').": {$bodyType}";
        } elseif ($method === 'get') {
            $args[] = 'params?: Query';
        }
        $args[] = 'config?: AxiosRequestConfig';
        $data = $op['responses']['200']['content']['application/json']['schema']['allOf'][1]['properties']['data'] ?? [];
        $answer = 'ApiResponse<'.self::answer($data).'>';

        $call = match (true) {
            $method === 'get' => "api.get<{$answer}>({$url}, { params, ...config })",
            $method === 'delete' => "api.delete<{$answer}>({$url}, { ...config".($bodyType ? ', data: body' : '').' })',
            default => "api.{$method}<{$answer}>({$url}, ".($bodyType ? 'body' : 'undefined').', config)',
        };
        $lines[] = '/** '.strtoupper($method).' /api/v1'.$path.' · '.$op['x-authz'].' */';
        $lines[] = "export const {$name} = (".implode(', ', $args).'): Promise<'.$answer.'> =>';
        $lines[] = "    {$call}.then((r) => r.data);";

        return $lines;
    }

    private static function answer(array $s): string
    {
        if (isset($s['$ref'])) {
            return class_basename($s['$ref']);
        }
        if (isset($s['allOf'])) {
            return 'Paginated<'.class_basename($s['allOf'][1]['properties']['data']['items']['$ref']).'>';
        }
        if (($s['type'] ?? null) === 'array' && isset($s['items']['$ref'])) {
            return class_basename($s['items']['$ref']).'[]';
        }

        return 'unknown';
    }

    /** A TypeScript type for a JSON schema (the subset OpenApiSpec writes). */
    public static function ts(mixed $s, string $indent): string
    {
        $s = (array) $s;
        $type = match (true) {
            isset($s['enum']) => implode(' | ', array_map(fn ($v) => is_string($v) ? "'".addslashes($v)."'" : json_encode($v), $s['enum'])),
            ($s['format'] ?? null) === 'binary' => 'Blob',
            ($s['type'] ?? null) === 'object' || isset($s['properties']) => self::object($s, $indent),
            ($s['type'] ?? null) === 'array' => self::wrap(self::ts($s['items'] ?? [], $indent)).'[]',
            in_array($s['type'] ?? null, ['integer', 'number'], true) => 'number',
            ($s['type'] ?? null) === 'boolean' => 'boolean',
            ($s['type'] ?? null) === 'string' => 'string',
            default => 'unknown',
        };

        return ! empty($s['nullable']) ? $type.' | null' : $type;
    }

    private static function wrap(string $t): string
    {
        return str_contains($t, ' ') && ! str_starts_with($t, '{') ? "({$t})" : $t;
    }

    private static function object(array $s, string $indent): string
    {
        $props = (array) ($s['properties'] ?? []);
        if (! $props) {
            return 'Record<string, unknown>';
        }
        $required = $s['required'] ?? [];
        $lines = ['{'];
        foreach ($props as $k => $v) {
            $key = preg_match('/^[A-Za-z_$][\w$]*$/', (string) $k) ? $k : "'{$k}'";
            $lines[] = $indent.'    '.$key.(in_array($k, $required, true) ? '' : '?').': '.self::ts($v, $indent.'    ').';';
        }
        $lines[] = $indent.'}';

        return implode("\n", $lines);
    }
}
