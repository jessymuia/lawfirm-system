<?php

namespace App\Api;

/**
 * ENG-15: the web app's TypeScript types for the API, generated from the v1 Resources' declared shapes
 * (Resource::SHAPE). `php artisan api:types` writes them; ApiShapesTest fails when the file is stale or a shape no
 * longer matches what its resource returns.
 *
 * Shape types: int, string, bool, decimal (a money/quantity string such as "1250.00"), date (d/m/Y string),
 * int[] (list of ids); a leading ? makes it nullable.
 */
class TypeScriptTypes
{
    public const FILE = 'resources/js/src/api/types.generated.ts';

    /** @return array<string, array<string, string>> TypeScript name => shape */
    public static function shapes(): array
    {
        $out = [];
        foreach (glob(app_path('Http/Resources/V1/*Resource.php')) as $file) {
            $class = 'App\\Http\\Resources\\V1\\'.basename($file, '.php');
            $out[substr(basename($file, '.php'), 0, -strlen('Resource'))] = $class::SHAPE;
        }
        ksort($out);

        return $out;
    }

    public static function render(): string
    {
        $lines = [
            '// Generated by `php artisan api:types` from app/Http/Resources/V1/*::SHAPE (ENG-15). Do not edit by hand.',
            '',
            '/** A decimal sent as a string, e.g. "1250.00" (money, hours). */',
            'export type Decimal = string;',
            '/** A date as the API shows it: d/m/Y. */',
            'export type DisplayDate = string;',
            '',
            '/** Every answer of the API. */',
            'export interface ApiResponse<T> {',
            '    success: boolean;',
            '    message: string;',
            '    data: T;',
            '    /** A machine-readable reason on some refusals (e.g. legal_hold, direct_uploads_unavailable). */',
            '    code?: string;',
            '    /** Validation errors on a 422. */',
            '    errors?: Record<string, string[]>;',
            '}',
            '',
            '/** A page of a list (ENG-16: lists always paginate). */',
            'export interface Paginated<T> {',
            '    data: T[];',
            '    current_page: number;',
            '    last_page: number;',
            '    per_page: number;',
            '    total: number;',
            '}',
        ];
        foreach (self::shapes() as $name => $shape) {
            $lines[] = '';
            $lines[] = "export interface {$name} {";
            foreach ($shape as $key => $type) {
                $lines[] = "    {$key}: ".self::ts($type).';';
            }
            $lines[] = '}';
        }

        return implode("\n", $lines)."\n";
    }

    public static function ts(string $type): string
    {
        $nullable = str_starts_with($type, '?');
        $base = match (ltrim($type, '?')) {
            'int' => 'number',
            'string' => 'string',
            'bool' => 'boolean',
            'decimal' => 'Decimal',
            'date' => 'DisplayDate',
            'int[]' => 'number[]',
            default => throw new \InvalidArgumentException("Unknown shape type [{$type}]"),
        };

        return $nullable ? "{$base} | null" : $base;
    }
}
